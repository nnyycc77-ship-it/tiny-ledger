"""Tests for agents/local-quotes/local_quotes.py (issue #76). Standard library only, no network.

Run:  python3 -m unittest discover -s agents/local-quotes/tests -v

(The module is test_agent.py, not test_local_quotes.py, so its name does not
clash with the CI loader tools/tests/test_local_quotes.py.)

Fixtures: everything under tests/fixtures is SYNTHETIC. The seven provider
pages, the candidate index and the request were written by hand, because no
provider directory or provider site is reachable from the build container
(probe recorded on issue #76), following the coordinator's #75 ruling for
labelled synthetic pages. Each page says so in its first line and
provenance.json repeats it with a sha256 per file. The outreach log's drafts
were generated by local_quotes.py itself from that store; every send time,
reply and reply date in it was entered by hand to simulate a collection
window (test_cli_timeline_reproduces_the_fixture_log replays it). No
message was sent and no provider replied. Pages DERIVED in a test from a
fixture page, with one stated change, are labelled where they are built.
"""

import contextlib
