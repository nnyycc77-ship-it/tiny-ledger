import shutil
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import local_quotes as lq  # noqa: E402

FIX = HERE / "fixtures"
REQUEST = FIX / "request.json"
LOG = FIX / "outreach-log.json"
AFTER_WINDOW = "2026-11-05T09:00:00Z"
IN_WINDOW = "2026-11-03T12:00:00Z"


def run(argv):
    out, err = io.StringIO(), io.StringIO()
    code = lq.main(argv, env={}, stdout=out, stderr=err)
    return code, out.getvalue(), err.getvalue()


def fixture_log():
    data = json.loads(LOG.read_text(encoding="utf-8"))
    data.pop("_label", None)
    return data


class TempStore:
    """A copy of the fixture store a test may change."""

    def __enter__(self):
        self.dir = Path(tempfile.mkdtemp())
        shutil.copytree(FIX, self.dir / "s")
        return self.dir / "s"

    def __exit__(self, *exc):
        shutil.rmtree(self.dir)


class Store(unittest.TestCase):
    def test_fixture_store_loads_and_is_labelled_synthetic(self):
        store = lq.load_store(FIX)
        self.assertEqual(len(store["pages"]), 7)
        self.assertEqual(store["source"]["label"], "SYNTHETIC")
        for page in store["pages"]:
            self.assertEqual(page.label, "SYNTHETIC")
            self.assertIn("SYNTHETIC", page.lines[0])

    def test_edited_page_is_refused(self):
        with TempStore() as s:
            p = s / "providers" / "barton-creek.html"
            p.write_text(p.read_text(encoding="utf-8").replace("$1,450", "$1,350"), encoding="utf-8")
            with self.assertRaises(lq.FetchError):
                lq.load_store(s)

    def test_provenance_url_must_match_the_index(self):
        with TempStore() as s:
            prov = json.loads((s / "provenance.json").read_text(encoding="utf-8"))
            prov["providers/eastside.html"]["url"] = "https://elsewhere.invalid/"
            (s / "provenance.json").write_text(json.dumps(prov), encoding="utf-8")
            with self.assertRaises(lq.FetchError):
                lq.load_store(s)


class Request(unittest.TestCase):
    def test_fixture_request_validates(self):
        req = lq.load_request(REQUEST)
        self.assertEqual((req["service"], req["location"], req["budget_max_usd"]), ("plumbing", "Austin, TX", 2500))

    def test_bad_requests_are_refused(self):
        good = json.loads(REQUEST.read_text(encoding="utf-8"))
        for change in ({"service": ""}, {"job_details": None}, {"response_deadline_utc": "next Friday"},
                       {"budget_max_usd": -5}, {"budget_min_usd": 3000}, {"follow_up_after_hours": 0}):
            with self.subTest(change=change):
                with self.assertRaises(lq.ConfigError):
                    lq.validate_request(dict(good, **change))


class Filter(unittest.TestCase):
    def setUp(self):
        self.req = lq.load_request(REQUEST)
        self.verified, self.excluded = lq.classify(self.req, lq.load_store(FIX))

    def test_matched_providers_are_verified_with_evidence(self):
        ids = [r["page"].provider_id for r in self.verified]
        self.assertEqual(ids, ["barton-creek", "riverside-rooter", "south-congress", "mueller-pipe", "eastside"])
        for r in self.verified:
            for claim in (r["service"], r["area"]):
                self.assertEqual(claim.excerpt, r["page"].lines[claim.line_no - 1])
                self.assertNotIn("<title", claim.excerpt)

    def test_mismatched_area_and_denied_service_are_excluded(self):
        reasons = {p.provider_id: (reason, claim) for p, reason, claim in self.excluded}
        self.assertIn("area: no line on the page names \"Austin\"; not verified, not inferred", reasons["round-rock"][0])
        self.assertIn("the page says it does not", reasons["hyde-park-electric"][0])
        self.assertIn("We do not do plumbing", reasons["hyde-park-electric"][1].excerpt)

    def test_a_business_name_alone_does_not_verify_the_service(self):
        # DERIVED from round-rock.html: only its title and heading name plumbing.
        page = lq.Page("x", "Round Rock Plumbing Co", "https://round-rock-plumbing.invalid/", "", "\n".join([
            "<title>Round Rock Plumbing Co</title>", "<h1>Round Rock Plumbing Co</h1>", "<p>Serving Austin.</p>"]), "DERIVED")
        verified, excluded = lq.classify(self.req, {"source": {}, "pages": [page]})
        self.assertEqual(verified, [])
        self.assertTrue(excluded[0][1].startswith("service:"))

    def test_channels_are_read_from_the_page(self):
        rows = {r["page"].provider_id: r for r in self.verified}
        self.assertEqual(lq.written_channels(rows["barton-creek"]["channels"]), ["email", "web_form"])
        self.assertEqual(rows["barton-creek"]["channels"]["email"].value, "quotes@barton-creek-plumbing.invalid")
        self.assertEqual(lq.written_channels(rows["riverside-rooter"]["channels"]), ["web_form", "directory_message"])
        self.assertEqual(lq.written_channels(rows["mueller-pipe"]["channels"]), [])
        # SYNTHETIC fixture number from mueller-pipe.html (555-01xx is reserved for fiction).
        self.assertEqual(rows["mueller-pipe"]["channels"]["phone"].value, "(512) 555-0147")


class Outreach(unittest.TestCase):
    def setUp(self):
        self.req = lq.load_request(REQUEST)
        self.store = lq.load_store(FIX)
        self.log = {"hire_id": None, "providers": {}}

    def test_first_drafts_go_to_verified_providers_only(self):
        drafted = lq.draft_initial(self.req, self.store, self.log, "2026-11-01T14:00:00Z")
        self.assertEqual(drafted, ["barton-creek", "riverside-rooter", "south-congress", "eastside"])
        self.assertTrue(self.log["providers"]["mueller-pipe"]["phone_only"])
        self.assertNotIn("round-rock", self.log["providers"])
        self.assertNotIn("hyde-park-electric", self.log["providers"])
        self.assertEqual(self.log["providers"]["barton-creek"]["attempts"][0]["channel"], "email")
        self.assertEqual(self.log["providers"]["riverside-rooter"]["attempts"][0]["channel"], "web_form")

    def test_draft_discloses_and_asks_for_a_quote_only(self):
        lq.draft_initial(self.req, self.store, self.log, "2026-11-01T14:00:00Z")
        text = self.log["providers"]["barton-creek"]["attempts"][0]["text"]
        for phrase in ("on behalf of a customer", "automated assistant", "we will stop",
                       "only collecting quotes", self.req["job_details"], self.req["timing"], "up to 2500 USD",
                       "quotes@barton-creek-plumbing.invalid"):
            self.assertIn(phrase, text)
        self.assertIsNone(lq.EMAIL_RE.search(text.replace("quotes@barton-creek-plumbing.invalid", "")))

    def sent_log(self):
        lq.draft_initial(self.req, self.store, self.log, "2026-11-01T14:00:00Z")
        lq.record_sent(self.log, "riverside-rooter", "web_form", "2026-11-01T15:05:00Z")
        return self.log

    def test_follow_up_waits_for_the_interval(self):
        log = self.sent_log()
        self.assertEqual(lq.draft_follow_ups(self.req, self.store, log, "2026-11-02T15:00:00Z"), [])
        self.assertEqual(lq.draft_follow_ups(self.req, self.store, log, "2026-11-03T16:00:00Z"), ["riverside-rooter"])
        attempt = log["providers"]["riverside-rooter"]["attempts"][1]
        self.assertEqual((attempt["channel"], attempt["follow_up"]), ("directory_message", True))
        self.assertIn("Following up on our web form of 2026-11-01T15:05:00Z", attempt["text"])

    def test_no_follow_up_after_the_window_or_a_reply_or_when_channels_run_out(self):
        log = self.sent_log()
        self.assertEqual(lq.draft_follow_ups(self.req, self.store, log, "2026-11-04T17:00:00Z"), [])
        lq.draft_follow_ups(self.req, self.store, log, "2026-11-03T16:00:00Z")
        lq.record_sent(log, "riverside-rooter", "directory_message", "2026-11-03T16:10:00Z")
        self.assertEqual(lq.draft_follow_ups(self.req, self.store, log, "2026-11-04T16:59:00Z"), [])
        lq.record_reply(log, "riverside-rooter", "2026-11-04T10:00:00Z", "We can come Monday.")
        self.assertEqual(log["providers"]["riverside-rooter"]["reply"]["availability"], "available as stated")

    def test_further_email_at_a_different_time_after_other_channels(self):
        # The proposal: a further email attempt at a different time, after the other published channels.
        lq.draft_initial(self.req, self.store, self.log, "2026-11-01T14:00:00Z")
        lq.record_sent(self.log, "barton-creek", "email", "2026-11-01T15:00:00Z")
        self.assertIn("barton-creek", lq.draft_follow_ups(self.req, self.store, self.log, "2026-11-03T15:30:00Z"))
        lq.record_sent(self.log, "barton-creek", "web_form", "2026-11-03T15:40:00Z")
        self.assertNotIn("barton-creek", lq.draft_follow_ups(self.req, self.store, self.log, "2026-11-04T09:00:00Z"))
        req = dict(self.req, response_deadline_utc="2026-11-09T17:00:00Z")
        self.assertIn("barton-creek", lq.draft_follow_ups(req, self.store, self.log, "2026-11-05T16:00:00Z"))
        channels = [a["channel"] for a in self.log["providers"]["barton-creek"]["attempts"]]
        self.assertEqual(channels, ["email", "web_form", "email"])
        lq.record_sent(self.log, "barton-creek", "email", "2026-11-05T16:10:00Z")
        self.assertNotIn("barton-creek", lq.draft_follow_ups(req, self.store, self.log, "2026-11-08T16:00:00Z"))

    def test_record_guards(self):
        with self.assertRaises(lq.ConfigError):
            lq.record_sent(self.log, "barton-creek", "email", "2026-11-01T15:00:00Z")  # no draft yet
        lq.draft_initial(self.req, self.store, self.log, "2026-11-01T14:00:00Z")
        with self.assertRaises(lq.ConfigError):
            lq.record_reply(self.log, "barton-creek", "2026-11-02T10:00:00Z", "Yes")  # not sent yet
        with self.assertRaises(lq.ConfigError):
            lq.record_sent(self.log, "barton-creek", "web_form", "2026-11-01T15:00:00Z")  # no web form draft
        with self.assertRaises(lq.ConfigError):
            lq.record_sent(self.log, "barton-creek", "email", "tomorrow")


class DryRun(unittest.TestCase):
    """The dry run on the fixtures: matched, mismatched area and no response providers."""

    def report(self, now):
        code, out, err = run(["run", "--request", str(REQUEST), "--store", str(FIX), "--log", str(LOG), "--now", now])
        self.assertEqual(code, 0, err)
        return out

    def test_after_the_window_non_responders_are_reported_with_dated_attempts(self):
        out = self.report(AFTER_WINDOW)
        self.assertIn("(closed at this run)", out)
        self.assertIn("- Riverside Rooter: no response after: web form sent 2026-11-01T15:05:00Z; "
                      "directory message sent 2026-11-03T16:10:00Z", out)
        self.assertIn("Candidates checked: 7. Verified for the service and area: 5. Contacted: 4. Replied: 3. "
                      "Phone only: 1. Excluded: 2.", out)

    def test_inside_the_window_they_are_awaiting_not_silent(self):
        out = self.report(IN_WINDOW)
        self.assertIn("awaiting reply (so far: web form sent 2026-11-01T15:05:00Z", out)
        self.assertIn("The collection window is still open", out)

    def test_comparison_is_tied_to_replies_or_published_pricing(self):
        out = self.report(AFTER_WINDOW)
        row = [l for l in out.splitlines() if l.startswith("| Barton Creek Plumbing |")][0]
        self.assertIn("reply: We can replace the 50 gallon gas unit for $1,980 total", row)
        self.assertIn("available as stated", row)
        self.assertIn("We will need access to the garage", row)
        self.assertIn("| fixed or total, as stated | not over the budget limit of 2500 USD: $1,980 stated", row)
        rooter = [l for l in out.splitlines() if l.startswith("| Riverside Rooter |")][0]
        self.assertIn("published: Service call fee $89, waived if we do the work.", rooter)
        self.assertIn("published price only ($89 stated on the page), not a quote for this job", rooter)
        self.assertIn("| not confirmed |", rooter)
        east = [l for l in out.splitlines() if l.startswith("| Eastside Plumbing |")][0]
        self.assertIn("| declined |", east)
        self.assertIn("| not stated |", east)

    def test_estimate_over_budget_and_site_visit_are_marked(self):
        out = self.report(AFTER_WINDOW)
        row = [l for l in out.splitlines() if l.startswith("| South Congress Plumbing |")][0]
        self.assertIn("| estimate | OVER the budget limit of 2500 USD: $2,700 stated by the provider (estimate) |", row)
        self.assertIn("reply: We would need a site visit first to confirm the price.", row)
        self.assertIn("reply: The permit and disposal of the old unit are extra.", row)

    def test_differences_in_what_quotes_cover_are_pointed_out(self):
        out = self.report(AFTER_WINDOW)
        section = out.split("## What the quotes cover", 1)[1].split("\n## ", 1)[0]
        self.assertIn("The quotes cover different things", section)
        self.assertIn("- **permit**: included by Barton Creek Plumbing; excluded by South Congress Plumbing", section)
        self.assertIn("- **disposal of the old unit**: included by Barton Creek Plumbing; excluded by South Congress Plumbing",
                      section)
        self.assertNotIn("**labor**", section)  # both quotes state labor
        self.assertNotIn("Riverside Rooter", section)  # a published fee is not a quote

    def test_next_steps_book_nothing(self):
        out = self.report(AFTER_WINDOW)
        steps = out.split("## Next steps for the buyer", 1)[1].split("\n## ", 1)[0]
        self.assertIn("The agent books nothing and accepts no quote", steps)
        self.assertIn("South Congress Plumbing needs a site visit before a firm price", steps)
        self.assertIn("South Congress Plumbing's stated price is over your budget limit", steps)
        self.assertIn("Mueller Pipe Pros publishes only a phone number", steps)

    def test_excluded_and_phone_only_sections(self):
        out = self.report(AFTER_WINDOW)
        self.assertIn("- Round Rock Plumbing Co <https://round-rock-plumbing.invalid/>: area:", out)
        self.assertIn("- Hyde Park Electric <https://hyde-park-electric.invalid/>: service:", out)
        # SYNTHETIC fixture number from mueller-pipe.html.
        self.assertIn("- Mueller Pipe Pros: only a phone number is published ((512) 555-0147)", out)

    def test_every_quoted_page_line_is_verbatim(self):
        out = self.report(AFTER_WINDOW)
        pages = {p.url: p for p in lq.load_store(FIX)["pages"]}
        lines = out.splitlines()
        checked = 0
        for i, line in enumerate(lines):
            if line.strip().startswith("Source: <") and "(line " in line:
                url = line.split("<", 1)[1].split(">", 1)[0]
                no = int(line.rsplit("(line ", 1)[1].rstrip(")"))
                self.assertEqual(lines[i + 2].strip(), pages[url].lines[no - 1].strip())
                checked += 1
        self.assertGreater(checked, 15)


class Cli(unittest.TestCase):
    def test_cli_timeline_reproduces_the_fixture_log(self):
        tmp = Path(tempfile.mkdtemp())
        try:
            log = str(tmp / "log.json")
            base = ["--request", str(REQUEST), "--store", str(FIX), "--log", log]
            steps = [
                ["draft"] + base + ["--now", "2026-11-01T14:00:00Z"],
                ["record-sent", "barton-creek", "--log", log, "--channel", "email", "--when", "2026-11-01T15:00:00Z"],
                ["record-sent", "riverside-rooter", "--log", log, "--channel", "web_form", "--when", "2026-11-01T15:05:00Z"],
                ["record-sent", "south-congress", "--log", log, "--channel", "email", "--when", "2026-11-01T15:08:00Z"],
                ["record-sent", "eastside", "--log", log, "--channel", "email", "--when", "2026-11-01T15:10:00Z"],
                ["record-reply", "barton-creek", "--log", log, "--when", "2026-11-02T10:30:00Z", "--text",
                 fixture_log()["providers"]["barton-creek"]["reply"]["text"]],
                ["record-reply", "eastside", "--log", log, "--when", "2026-11-02T12:00:00Z", "--text",
                 fixture_log()["providers"]["eastside"]["reply"]["text"]],
                ["record-reply", "south-congress", "--log", log, "--when", "2026-11-02T16:00:00Z", "--text",
                 fixture_log()["providers"]["south-congress"]["reply"]["text"]],
                ["follow-up"] + base + ["--now", "2026-11-03T16:00:00Z"],
                ["record-sent", "riverside-rooter", "--log", log, "--channel", "directory_message", "--when", "2026-11-03T16:10:00Z"],
                ["follow-up"] + base + ["--now", "2026-11-04T18:00:00Z"],
            ]
            for step in steps:
                code, _, err = run(step)
                self.assertEqual(code, 0, (step[0], err))
            self.assertEqual(json.loads(Path(log).read_text(encoding="utf-8")), fixture_log())
        finally:
            shutil.rmtree(tmp)

    def test_send_is_refused(self):
        for argv in (["send", "barton-creek", "--log", str(LOG)],
                     ["send", "barton-creek", "--log", str(LOG), "--execute"],
                     ["send", "barton-creek", "--log", str(LOG), "--execute", "--hire-id", "h-1"]):
            with self.subTest(argv=argv):
                code, out, err = run(argv)
                self.assertEqual((code, out), (2, ""))
                self.assertIn("send:", err)

    def test_bad_input_fails_closed_with_no_report(self):
        code, out, err = run(["run", "--request", str(REQUEST), "--store", str(FIX), "--now", "soon"])
        self.assertEqual((code, out), (2, ""))
        code, out, err = run(["run", "--request", str(FIX / "missing.json"), "--store", str(FIX)])
        self.assertEqual((code, out), (2, ""))

    def test_capture_writes_provenance_and_refuses_non_200(self):
        tmp = Path(tempfile.mkdtemp())
        try:
            page = b"<p>SYNTHETIC page served by a fake fetcher</p>"
            ok = lambda url: ("HTTP 200 OK", [("Content-Type", "text/html"), ("Set-Cookie", "s=SYNTHETIC")], page)
            rel, _ = lq.capture("https://p.invalid/", tmp, "p-one", "P One", fetcher=ok)
            prov = json.loads((tmp / "provenance.json").read_text(encoding="utf-8"))[rel]
            self.assertEqual(prov["sha256"], lq.sha256_bytes(page))
            self.assertNotIn("Set-Cookie: s=SYNTHETIC", prov["headers"])
            self.assertEqual(len(lq.load_store(tmp)["pages"]), 1)
            bad = lambda url: ("HTTP 404 Not Found", [], b"")
            with self.assertRaises(lq.FetchError):
                lq.capture("https://p.invalid/x", tmp, "p-two", "P Two", fetcher=bad)
        finally:
            shutil.rmtree(tmp)


