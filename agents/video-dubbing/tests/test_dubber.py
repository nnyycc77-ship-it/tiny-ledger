"""Offline tests for the video dubbing agent.

FIXTURE LABEL: every input is generated by this test. The source video is
an ffmpeg test pattern; its speech is synthesized with ffmpeg's flite
filter (a stock synthetic voice, no real person's voice) over a generated
two tone music bed. The segments file, the glossary translations and the
consent records below are example data written for this test. No real
person's voice is cloned or imitated anywhere. Nothing is downloaded and
no network is used.

Needs ffmpeg with the flite filter; the media tests are skipped, not
failed, without it.
"""

import io
import json
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import dubber  # noqa: E402
import providers  # noqa: E402
import sync  # noqa: E402


def _has_flite():
    if shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None:
        return False
    out = subprocess.run(["ffmpeg", "-hide_banner", "-filters"], stdout=subprocess.PIPE,
                         stderr=subprocess.PIPE).stdout.decode()
    return " flite " in out


HAVE_MEDIA = _has_flite()
DURATION = 20.0

# Example data: the source segments (what the generated speech says) and
# their speakers; two speakers, as in an interview.
SEGMENTS = [
    (1.0, 4.0, "Welcome to the Hojo storage guide", "A"),
    (5.0, 7.0, "Keep the battery cool", "B"),
    (9.0, 11.0, "Charge it to eighty percent", "A"),
    (11.2, 14.0, "Then store it on NEAR shelf mode for winter", "B"),
]

# Example data: test glossary. Lengths are chosen against the stub voice
# (0.06 s per character plus 0.2 s) so each sync path is exercised:
# seg 0 fits; seg 1 breathes into the genuine pause after it; seg 2 is
# compressed (no genuine pause follows); seg 3 needs its tightened wording.
GLOSSARY = {
    "es": {
        "0": {"text": "Bienvenidos a la guia de Hojo",
              "note": "example note: greeting adapted to a plural audience"},
        "1": "Mantenga la bateria siempre fresca hoy",
        "2": "Carguela hasta ochenta por ciento",
        "3": {"text": "Despues guardela en el modo estante NEAR durante todo el invierno largo",
              "shorter": ["Luego, modo estante NEAR en invierno"]},
    },
    "fr": {
        "0": "Bienvenue dans le guide Hojo",
        "1": "Gardez la batterie au frais tous les jours",
        "2": "Chargez a quatre-vingts pour cent",
        "3": {"text": "Puis rangez-la en mode etagere NEAR pendant tout le long hiver froid",
              "shorter": ["Puis mode etagere NEAR en hiver"]},
    },
}
TERMS = "Hojo,NEAR"
FULL_CONSENT = {"basis": "speaker_consent", "consent_record": "example-consent-ref-001",
                "rights_confirmed": True, "confirmed_by": "example rights holder"}


def seg(i, start, end, text="x"):
    return providers.Segment(i, start, end, text)


class SyncTests(unittest.TestCase):
    def test_fits_as_spoken(self):
        fit = sync.fit_line(seg(0, 0, 3), None, ["a"], lambda t: 2.0)
        self.assertEqual((fit.stretch, fit.tightened, fit.flagged), (1.0, False, False))

    def test_tighten_before_stretch(self):
        lengths = {"long": 3.5, "short": 1.9}
        fit = sync.fit_line(seg(0, 0, 2), None, ["long", "short"], lengths.get)
        self.assertEqual((fit.wording, fit.tightened, fit.stretch), ("short", True, 1.0))

    def test_stretch_within_limit_is_flagged(self):
        fit = sync.fit_line(seg(0, 0, 2), seg(1, 2.1, 3), ["a"], lambda t: 2.2)
        self.assertTrue(fit.flagged)
        self.assertLessEqual(fit.stretch, sync.MAX_STRETCH)
        self.assertIn("compressed", fit.note())

    def test_breathe_only_into_genuine_pause(self):
        fit = sync.fit_line(seg(0, 0, 2), seg(1, 3.0, 4), ["a"], lambda t: 2.6)
        self.assertGreater(fit.breathed, 0)
        self.assertLessEqual(fit.segment.start + fit.window, 3.0 - sync.MIN_GAP + 1e-9)
        with self.assertRaises(sync.SyncError):  # 0.2 s pause is not genuine
            sync.fit_line(seg(0, 0, 2), seg(1, 2.2, 4), ["a"], lambda t: 2.6)

    def test_unfittable_line_fails_closed(self):
        with self.assertRaises(sync.SyncError) as ctx:
            sync.fit_line(seg(4, 0, 1), None, ["a"], lambda t: 3.0)
        self.assertIn("segment 4", str(ctx.exception))


class ProtectionAndConsentTests(unittest.TestCase):
    def test_mask_keeps_terms_through_a_translator(self):
        out, _ = providers.StubTranslator().translate(
            seg(0, 0, 1, "Hojo runs on NEAR today"), "es", ["Hojo", "NEAR"])
        self.assertIn("Hojo", out)
        self.assertIn("NEAR", out)

    def test_lost_term_fails_closed(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "g.json"
            path.write_text(json.dumps({"es": {"0": "Bienvenidos a la guia"}}), encoding="utf-8")
            with self.assertRaises(providers.ProtectedTermError):
                providers.GlossaryTranslator(str(path)).translate(
                    seg(0, 0, 1, "Welcome to the Hojo guide"), "es", ["Hojo"])

    def test_own_voice_refuses_without_consent(self):
        with self.assertRaises(providers.ConsentError):
            providers.OwnVoice(None)
        for field in providers.CONSENT_FIELDS:
            partial = dict(FULL_CONSENT)
            partial[field] = {"basis": "buyer_says_so", "rights_confirmed": False}.get(field, "")
            with self.assertRaises(providers.ConsentError, msg=field):
                providers.OwnVoice(partial)

    def test_own_voice_with_consent_still_has_no_engine(self):
        with self.assertRaises(providers.ProviderError) as ctx:
            providers.OwnVoice(FULL_CONSENT)
        self.assertNotIsInstance(ctx.exception, providers.ConsentError)
        self.assertIn("no voice cloning engine", str(ctx.exception))

    def test_both_consent_bases_are_accepted_by_the_check(self):
        for basis in providers.CONSENT_BASES:
            providers.check_consent(dict(FULL_CONSENT, basis=basis))

    def test_stock_voices_are_distinct_per_speaker(self):
        flite = providers.FliteVoice("kal")
        self.assertEqual(flite.voice_for("A"), "kal")
        self.assertNotEqual(flite.voice_for("B"), "kal")
        stub = providers.StubVoice()
        self.assertNotEqual(stub.voice_for("A"), stub.voice_for("B"))

    def test_flite_refuses_other_languages(self):
        with self.assertRaises(providers.ProviderError):
            providers.FliteVoice().synthesize("hola", "es", "/tmp/unused.wav")


@unittest.skipUnless(HAVE_MEDIA, "ffmpeg with the flite filter is needed for the media tests")
class FixtureRunTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        cls.dir = Path(cls.tmp.name)
        cls.video = cls.dir / "guide.mp4"
        cls._make_video()
        cls.segments = cls.dir / "segments.json"
        cls.segments.write_text(json.dumps({
            "engine": "example segments written for this test",
            "segments": [{"start": a, "end": b, "text": t, "speaker": sp}
                         for a, b, t, sp in SEGMENTS]}),
            encoding="utf-8")
        cls.glossary = cls.dir / "glossary.json"
        cls.glossary.write_text(json.dumps(GLOSSARY), encoding="utf-8")
        cls.out = cls.dir / "out"
        cls.stdout = io.StringIO()
        cls.code = dubber.main(cls.base("run", cls.out) + ["--languages", "es,fr"],
                               stdout=cls.stdout, stderr=io.StringIO())
        cls.manifest = json.loads((cls.out / "manifest.json").read_text(encoding="utf-8"))

    @classmethod
    def base(cls, command, out):
        return [command, "--video", str(cls.video), "--segments", str(cls.segments),
                "--translator", "glossary", "--glossary", str(cls.glossary), "--voice", "stub",
                "--dnt", TERMS, "--out", str(out)]

    @classmethod
    def _make_video(cls):
        inputs, labels = [], []
        for k, (start, _, text, _) in enumerate(SEGMENTS):
            txt = cls.dir / ("line%d.txt" % k)
            txt.write_text(text, encoding="utf-8")
            inputs += ["-f", "lavfi", "-i", "flite=textfile='%s':voice=slt" % txt]
            labels.append(k)
        bed = len(SEGMENTS)
        inputs += ["-f", "lavfi", "-i",
                   "aevalsrc=exprs='0.05*sin(2*PI*196*t)+0.05*sin(2*PI*247*t)':s=44100:d=%s"
                   % DURATION]
        video = bed + 1
        inputs += ["-f", "lavfi", "-i", "testsrc2=s=320x180:r=15:d=%s" % DURATION]
        chains = ["[%d:a]aresample=44100,adelay=%d|%d[s%d]" % (k, int(SEGMENTS[k][0] * 1000),
                                                              int(SEGMENTS[k][0] * 1000), k)
                  for k in labels]
        mix = "%s[%d:a]amix=inputs=%d:normalize=0:duration=longest[a]" % (
            "".join("[s%d]" % k for k in labels), bed, len(labels) + 1)
        subprocess.run(["ffmpeg", "-nostdin", "-loglevel", "error", "-y"] + inputs +
                       ["-filter_complex", ";".join(chains + [mix]),
                        "-map", "%d:v" % video, "-map", "[a]", "-c:v", "libx264",
                        "-preset", "ultrafast", "-pix_fmt", "yuv420p", "-c:a", "aac",
                        "-t", str(DURATION), str(cls.video)], check=True)

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_run_succeeds_with_video_and_srt_per_language(self):
        self.assertEqual(self.code, 0)
        for lang in ("es", "fr"):
            self.assertTrue((self.out / ("guide.%s.mp4" % lang)).is_file())
            self.assertTrue((self.out / ("guide.%s.srt" % lang)).is_file())

    def test_durations_stay_within_tolerance(self):
        original = dubber.probe(str(self.video))
        for lang in ("es", "fr"):
            self.assertAlmostEqual(dubber.probe(str(self.out / ("guide.%s.mp4" % lang))),
                                   original, delta=0.15, msg=lang)

    def test_subtitles_carry_the_full_translation(self):
        srt = (self.out / "guide.es.srt").read_text(encoding="utf-8")
        self.assertIn(GLOSSARY["es"]["3"]["text"], srt)  # full wording, though tightened was spoken
        self.assertEqual(srt.count(" --> "), len(SEGMENTS))

    def test_sync_paths_and_flagged_segments_are_reported(self):
        lines = {l["segment"]: l for l in self.manifest["lines"]["es"]}
        self.assertEqual(lines[0]["note"], "fits as spoken")
        self.assertIn("into the following pause", lines[1]["note"])
        self.assertFalse(lines[1]["flagged"])
        self.assertTrue(lines[2]["flagged"])
        self.assertIn("compressed", lines[2]["note"])
        self.assertIn("tightened", lines[3]["note"])
        report = (self.out / "report.md").read_text(encoding="utf-8")
        self.assertIn("segment 2", report)
        self.assertIn("compressed", report)
        self.assertIn("not true source separation", report)

    def test_every_line_is_dubbed_in_every_language(self):
        for lang in ("es", "fr"):
            self.assertEqual(len(self.manifest["lines"][lang]), len(SEGMENTS))
        self.assertIn("Untranslated lines: none",
                      (self.out / "report.md").read_text(encoding="utf-8"))

    def test_each_speaker_gets_a_distinct_voice(self):
        voices = self.manifest["speakers"]
        self.assertEqual(sorted(voices), ["A", "B"])
        self.assertNotEqual(voices["A"], voices["B"])
        self.assertEqual({l["speaker"] for l in self.manifest["lines"]["es"]}, {"A", "B"})

    def test_translation_notes_reach_the_report(self):
        report = (self.out / "report.md").read_text(encoding="utf-8")
        self.assertIn("Hard to translate, segment 0", report)

    def test_spoken_subtitle_mode_matches_the_voiced_wording(self):
        out = self.dir / "spoken"
        code = dubber.main(self.base("run", out) + ["--languages", "es", "--subtitles", "spoken"],
                           stdout=io.StringIO(), stderr=io.StringIO())
        self.assertEqual(code, 0)
        srt = (out / "guide.es.srt").read_text(encoding="utf-8")
        self.assertIn(GLOSSARY["es"]["3"]["shorter"][0], srt)
        self.assertNotIn(GLOSSARY["es"]["3"]["text"], srt)

    def test_protected_terms_survive_in_outputs(self):
        for lang in ("es", "fr"):
            srt = (self.out / ("guide.%s.srt" % lang)).read_text(encoding="utf-8")
            self.assertIn("Hojo", srt)
            self.assertIn("NEAR", srt)

    def test_plan_writes_nothing(self):
        out = self.dir / "plan-out"
        code = dubber.main(self.base("plan", out) + ["--languages", "es"],
                           stdout=io.StringIO(), stderr=io.StringIO())
        self.assertEqual(code, 0)
        self.assertFalse(out.exists())

    def test_own_voice_job_refuses_without_consent_and_writes_nothing(self):
        out = self.dir / "own-voice"
        args = self.base("run", out) + ["--languages", "es"]
        args[args.index("stub")] = "own-voice"
        stderr = io.StringIO()
        self.assertEqual(dubber.main(args, stdout=io.StringIO(), stderr=stderr), 2)
        self.assertIn("own-voice", stderr.getvalue())
        self.assertFalse(out.exists())

    def test_unfittable_line_stops_the_run(self):
        tight = dict(GLOSSARY)
        tight["es"] = dict(GLOSSARY["es"], **{"2": "Carguela siempre hasta el ochenta por ciento exacto"})
        path = self.dir / "tight.json"
        path.write_text(json.dumps(tight), encoding="utf-8")
        out = self.dir / "tight-out"
        args = self.base("run", out) + ["--languages", "es"]
        args[args.index(str(self.glossary))] = str(path)
        stderr = io.StringIO()
        self.assertEqual(dubber.main(args, stdout=io.StringIO(), stderr=stderr), 2)
        self.assertIn("segment 2", stderr.getvalue())
        self.assertFalse(out.exists())


if __name__ == "__main__":
    unittest.main()
